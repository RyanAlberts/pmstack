#!/usr/bin/env python3
"""
End-to-end test for bin/eval-report.py.

Runs the real generator (via its CLI) against the bundled walkthrough run and
asserts the produced HTML is correct, shareable (self-contained, no external
assets), and faithful to the source summary. Also checks the machine-written
summary format (bin/run-eval.py's write_summary output) and the error paths.

Stdlib only. No network. Exits 0 if every check passes, non-zero otherwise.
"""
from __future__ import annotations

import re
import subprocess
import sys
import tempfile
from pathlib import Path
from typing import NamedTuple

REPO = Path(__file__).resolve().parents[1]
GEN = REPO / "bin" / "eval-report.py"
BUNDLED_RUN = REPO / "examples" / "walkthrough-code-review" / "eval-runs" / "code-review-eval-2026-05-06"

# the machine-written summary shape (mirrors bin/run-eval.py write_summary)
MACHINE_SUMMARY = """# Eval Suite: Demo — run 2026-06-23T00:00:00+00:00

## Headline

| severity | passed | total |
|---|---|---|
| P0 | 2 | 3 |
| P1 | 1 | 1 |
| P2 | 0 | 0 |

- cases run: 4

## Metrics — per case

| case | severity | passed | metrics |
|---|---|---|---|
| tc-a | P0 | PASS | accuracy=0.9 |
| tc-b | P0 | FAIL | accuracy=0.4 |
| tc-c | P0 | PASS | accuracy=0.95 |
| tc-d | P1 | PASS | latency=120 |
"""


class Check(NamedTuple):
    name: str
    passed: bool
    detail: str


def run_gen(arg: str, out: Path) -> subprocess.CompletedProcess:
    return subprocess.run(
        [sys.executable, str(GEN), arg, "--out", str(out)],
        capture_output=True, text=True, cwd=str(REPO),
    )


def check_bundled() -> list[Check]:
    checks: list[Check] = []
    with tempfile.TemporaryDirectory() as td:
        out = Path(td) / "report.html"
        proc = run_gen(str(BUNDLED_RUN), out)
        ran = proc.returncode == 0 and out.exists()
        checks.append(Check("generator runs on bundled run (exit 0)", ran, proc.stderr.strip()[-200:]))
        if not ran:
            return checks
        h = out.read_text(encoding="utf-8")

        checks.append(Check("valid HTML envelope", h.lstrip().startswith("<!doctype html>") and h.rstrip().endswith("</html>"), ""))
        checks.append(Check("headline pass-rate rendered (9/11, 82%)", "9/11" in h and "82%" in h, ""))
        checks.append(Check("verdict hero present (Conditional, warn)", 'class="hero warn"' in h and "Conditional" in h, ""))

        missing_cases = [c for c in (f"tc-{i:02d}" for i in range(1, 13)) if c not in h]
        checks.append(Check("all 12 case ids present", not missing_cases, f"missing: {missing_cases}"))

        checks.append(Check("PASS cells color-coded", 'td class="pass"' in h, ""))
        checks.append(Check("FAIL cells color-coded", 'td class="fail"' in h, ""))
        checks.append(Check("metrics rows rendered", "security_correctness_precision" in h and "severity_calibration" in h, ""))

        checks.append(Check("footer badge + backlink", "Generated by pmstack" in h and "github.com/RyanAlberts/pmstack" in h, ""))

        # shareable = self-contained: no external stylesheet/script/img/@import/url(http)
        external = re.search(r'rel=["\']stylesheet|<script[^>]+src=|<img[^>]+src=["\']https?:|@import|url\(\s*https?:', h)
        checks.append(Check("self-contained (no external assets)", external is None, external.group(0) if external else ""))

        # no leftover raw markdown leaking into the body
        raw_table = re.search(r"(?m)^\s*\|\s.+\|\s*$", h) or "|---" in h
        raw_bold = re.search(r"\*\*[A-Za-z]", h)
        raw_head = re.search(r"(?m)^\s*##?\s", h)
        checks.append(Check("no raw markdown tables leaked", not raw_table, ""))
        checks.append(Check("no raw ** bold leaked", raw_bold is None, raw_bold.group(0) if raw_bold else ""))
        checks.append(Check("no raw markdown headers leaked", raw_head is None, raw_head.group(0) if raw_head else ""))

        # determinism: same input → byte-identical output
        out2 = Path(td) / "report2.html"
        run_gen(str(BUNDLED_RUN), out2)
        checks.append(Check("deterministic (byte-identical on re-run)", out.read_bytes() == out2.read_bytes(), ""))
    return checks


def check_machine_format() -> list[Check]:
    checks: list[Check] = []
    with tempfile.TemporaryDirectory() as td:
        summ = Path(td) / "summary.md"
        summ.write_text(MACHINE_SUMMARY, encoding="utf-8")
        out = Path(td) / "report.html"
        proc = run_gen(str(summ), out)
        ran = proc.returncode == 0 and out.exists()
        checks.append(Check("generator runs on machine-format summary", ran, proc.stderr.strip()[-200:]))
        if not ran:
            return checks
        h = out.read_text(encoding="utf-8")
        checks.append(Check("machine hero derived from headline table (P0 2/3)", "P0 2/3" in h, ""))
        checks.append(Check("machine per-case PASS/FAIL color-coded", 'td class="pass"' in h and 'td class="fail"' in h, ""))
    return checks


def check_error_paths() -> list[Check]:
    checks: list[Check] = []
    with tempfile.TemporaryDirectory() as td:
        # empty summary → non-zero exit
        empty = Path(td) / "summary.md"
        empty.write_text("   \n", encoding="utf-8")
        p1 = run_gen(str(empty), Path(td) / "o1.html")
        checks.append(Check("empty summary exits non-zero", p1.returncode != 0, f"rc={p1.returncode}"))
        # missing path → non-zero exit
        p2 = run_gen(str(Path(td) / "does-not-exist"), Path(td) / "o2.html")
        checks.append(Check("missing path exits non-zero", p2.returncode != 0, f"rc={p2.returncode}"))
        # run dir without summary.md → non-zero exit
        bare = Path(td) / "barerun"
        bare.mkdir()
        p3 = run_gen(str(bare), Path(td) / "o3.html")
        checks.append(Check("run dir without summary.md exits non-zero", p3.returncode != 0, f"rc={p3.returncode}"))
    return checks


def main() -> int:
    if not GEN.exists():
        print(f"FAIL — generator not found at {GEN}", file=sys.stderr)
        return 1
    if not BUNDLED_RUN.exists():
        print(f"FAIL — bundled run not found at {BUNDLED_RUN}", file=sys.stderr)
        return 1

    all_checks = check_bundled() + check_machine_format() + check_error_paths()

    print(f"\neval-report e2e — {len(all_checks)} checks\n")
    failures = [c for c in all_checks if not c.passed]
    for c in all_checks:
        mark = "✓" if c.passed else "✗"
        line = f"  {mark} {c.name}"
        if not c.passed and c.detail:
            line += f"   [{c.detail}]"
        print(line)

    if failures:
        print(f"\nFAIL — {len(failures)}/{len(all_checks)} checks failed")
        return 1
    print(f"\nPASS — all {len(all_checks)} checks passed")
    return 0


if __name__ == "__main__":
    sys.exit(main())
